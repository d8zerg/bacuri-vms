"""Generates the error definitions of the server and the client from the error catalog and checks the catalog.

Usage:
  errors.py cpp OUTPUT.hpp     C++ header with ErrorCode and its properties
  errors.py json OUTPUT.json   retry behavior of each code for the web client
  errors.py docs               writes the error reference in English and Russian
  errors.py check              the catalog against the OpenAPI contract, the server sources, the client messages and
                               the error reference
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "contracts/v1/errors.yaml"
RETRY = ("never", "after_change", "later", "user_action")
AUDIENCE = ("operators", "administrators", "services")
# Values of grpc::StatusCode.
GRPC = {
    "CANCELLED": 1, "UNKNOWN": 2, "INVALID_ARGUMENT": 3, "DEADLINE_EXCEEDED": 4, "NOT_FOUND": 5,
    "ALREADY_EXISTS": 6, "PERMISSION_DENIED": 7, "RESOURCE_EXHAUSTED": 8, "FAILED_PRECONDITION": 9,
    "ABORTED": 10, "OUT_OF_RANGE": 11, "UNIMPLEMENTED": 12, "INTERNAL": 13, "UNAVAILABLE": 14,
    "DATA_LOSS": 15, "UNAUTHENTICATED": 16,
}
NAME = re.compile(r"^[a-z][a-z0-9_]*$")


def load():
    catalog = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    categories, errors = catalog["categories"], catalog["errors"]
    problems = []
    for code, entry in errors.items():
        where = f"{CATALOG.name}: {code}"
        if not NAME.match(code):
            problems.append(f"{where}: the code is not snake_case")
        if set(entry) - {"surface"} != {"category", "http", "grpc", "retry", "audience", "description"}:
            problems.append(f"{where}: fields {sorted(entry)}")
            continue
        if entry.get("surface", "problem") not in {"problem", "map_state", "browser", "grpc"}:
            problems.append(f"{where}: unknown surface {entry['surface']}")
        if entry["category"] not in categories:
            problems.append(f"{where}: unknown category {entry['category']}")
        if not (isinstance(entry["http"], int) and 400 <= entry["http"] <= 599):
            problems.append(f"{where}: HTTP status {entry['http']}")
        if entry["grpc"] not in GRPC:
            problems.append(f"{where}: gRPC code {entry['grpc']}")
        if entry["retry"] not in RETRY:
            problems.append(f"{where}: retry {entry['retry']}")
        if entry["audience"] not in AUDIENCE:
            problems.append(f"{where}: audience {entry['audience']}")
    if problems:
        sys.exit("\n".join(problems))
    return categories, errors


def cpp(output):
    categories, errors = load()
    rows = ",\n".join(
        f'    ErrorInfo{{"{code}", ErrorCategory::{e["category"]}, {e["http"]}, {GRPC[e["grpc"]]}, '
        f'Retry::{e["retry"]}, Audience::{e["audience"]}, {str(e.get("surface", "problem") == "problem").lower()}}}'
        for code, e in errors.items())
    text = f"""#pragma once
// Generated by tools/errors.py from contracts/v1/errors.yaml.
#include <array>
#include <cstddef>
#include <cstdint>
#include <optional>
#include <string_view>

namespace bacuri::vms
{{
enum class ErrorCategory : std::uint8_t {{ {", ".join(categories)} }};
enum class Retry : std::uint8_t {{ {", ".join(RETRY)} }};
enum class Audience : std::uint8_t {{ {", ".join(AUDIENCE)} }};
enum class ErrorCode : std::uint16_t {{ {", ".join(errors)} }};

struct ErrorInfo {{
    std::string_view code;
    ErrorCategory category;
    // HTTP status of a Problem response and the value of grpc::StatusCode.
    int http, grpc;
    Retry retry;
    Audience audience;
    bool problem;
}};

inline constexpr std::array<ErrorInfo, {len(errors)}> error_catalog{{{{
{rows}}}}};

constexpr const ErrorInfo& info(ErrorCode code)
{{
    return error_catalog[static_cast<std::size_t>(code)];
}}

constexpr std::optional<ErrorCode> parse_error(std::string_view code)
{{
    for (std::size_t i = 0; i < error_catalog.size(); ++i)
        if (error_catalog[i].code == code)
            return static_cast<ErrorCode>(i);
    return std::nullopt;
}}
}} // namespace bacuri::vms
"""
    Path(output).parent.mkdir(parents=True, exist_ok=True)
    Path(output).write_text(text, encoding="utf-8")


def client(output):
    _, errors = load()
    data = {code: entry["retry"] for code, entry in errors.items()}
    Path(output).parent.mkdir(parents=True, exist_ok=True)
    Path(output).write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")


