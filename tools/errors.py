def reference(language):
    categories, errors = load()
    words = LANGUAGE[language]
    texts = message_texts(ROOT / "web/client/src/i18n/ru.ts")
    lines = [f"# {words['title']}", "", words["other"], "", words["intro"], ""]
    for category, description in categories.items():
        rows = [(code, e) for code, e in errors.items() if e["category"] == category]
        if not rows:
            continue
        lines += [f"## {CATEGORY_TITLES[language][category]}", ""]
        if language == "en":
            lines += [description, ""]
        lines += [words["columns"], "| --- | --- | --- | --- | --- |"]
        for code, e in rows:
            meaning = e["description"] if language == "en" else texts[f"error.{code}"]
            status = words["surface"].get(e.get("surface"), str(e["http"]))
            lines.append(f"| `{code}` | {status} | {words['retry'][e['retry']]} | "
                         f"{words['audience'][e['audience']]} | {meaning} |")
        lines.append("")
    return "\n".join(lines)


def docs():
    for language, words in LANGUAGE.items():
        words["file"].write_text(reference(language), encoding="utf-8")


def message_texts(path):
    return {m.group(1): json.loads(m.group(2)) for m in re.finditer(
        r'^\s*"([\w.]+)":\s*\n?\s*("(?:[^"\\]|\\.)*")\s*,', path.read_text(encoding="utf-8"), re.M)}


def messages(path):
    return set(re.findall(r'^\s*"error\.([a-z0-9_]+)":', path.read_text(encoding="utf-8"), re.M))


def check():
    _, errors = load()
    codes = set(errors)
    problems = []
    api = yaml.safe_load((ROOT / "contracts/v1/openapi.yaml").read_text(encoding="utf-8"))
    listed = set(api["components"]["schemas"]["Problem"]["properties"]["code"]["enum"])
    # Every failure response of the API carries a Problem body with a catalog code.
    for path, item in api["paths"].items():
        for method, operation in item.items():
            if not isinstance(operation, dict) or "operationId" not in operation:
                continue
            responses = operation["responses"]
            if "default" not in responses:
                problems.append(f"{method.upper()} {path}: missing shared HTTP failures")
            for status, response in responses.items():
                if status != "default" and not status.startswith(("4", "5")):
                    continue
                if "$ref" in response:
                    response = api["components"]["responses"][response["$ref"].rsplit("/", 1)[1]]
                if "application/problem+json" not in response.get("content", {}):
                    problems.append(f"{method.upper()} {path} {status}: the failure response has no Problem body")
    map_codes = set(api["components"]["schemas"]["MapPackageError"]["enum"])
    expected = {code for code, entry in errors.items() if entry.get("surface") == "map_state"} | {""}
    if map_codes != expected:
        problems.append(f"Map package error codes differ from the catalog: {sorted(map_codes ^ expected)}")
    problem = {code for code, e in errors.items() if e.get("surface", "problem") == "problem"}
    if listed - problem:
        problems.append(f"Problem codes outside the catalog: {sorted(listed - problem)}")
    if problem - listed:
        problems.append(f"Catalog codes missing from the Problem schema: {sorted(problem - listed)}")
    sent = set()
    for source in (ROOT / "src").rglob("*.cpp"):
        sent.update(re.findall(r"ErrorCode::([a-z0-9_]+)", source.read_text(encoding="utf-8")))
    if sent - codes:
        problems.append(f"Server codes outside the catalog: {sorted(sent - codes)}")
    # Every cause has a message, also a cause between services, which diagnostics of a site can show.
    shown = codes
    for language in ("ru", "en"):
        catalog = ROOT / f"web/client/src/i18n/{language}.ts"
        missing = shown - messages(catalog)
        extra = messages(catalog) - shown
        if missing:
            problems.append(f"{catalog.relative_to(ROOT)}: no message for {sorted(missing)}")
        if extra:
            problems.append(f"{catalog.relative_to(ROOT)}: messages for unknown codes {sorted(extra)}")
    for language, words in LANGUAGE.items():
        if not words["file"].is_file() or words["file"].read_text(encoding="utf-8") != reference(language):
            problems.append(f"{words['file'].relative_to(ROOT)} is outdated, run tools/errors.py docs")
    if problems:
        sys.exit("\n".join(problems))
    print(f"{len(codes)} error codes match the contract, the server and the client messages")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "cpp" and len(sys.argv) == 3:
        cpp(sys.argv[2])
    elif command == "json" and len(sys.argv) == 3:
        client(sys.argv[2])
    elif command == "docs":
        docs()
    elif command == "check":
        check()
    else:
        sys.exit(__doc__)
